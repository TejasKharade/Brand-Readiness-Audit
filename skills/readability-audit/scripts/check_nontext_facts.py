# Helpers
# ---------------------------------------------------------------------------

_IMAGE_EXT_RX = re.compile(r"\.(jpe?g|png|gif|webp|svg|avif|bmp|tiff?)$", re.I)

# Filler/CMS words that, joined with hyphens, make a slug rather than prose
# ("hero-banner-final"). Deliberately the same vocabulary as
# _AUTOGEN_FILENAME_RX's word list, checked per-segment rather than requiring
# the whole string to be one of these words plus a numeric suffix.
_FILLER_WORD_RX = re.compile(
    r"^(?:img|image|images|dsc|dscn|dscf|pxl|gopr|mvimg|pano|photo|pic|scan|"
    r"scanned|capture|screenshot|screen|snip|snap|untitled|unnamed|noname|new|"
    r"final|final2|finalfinal|copy|copyof|draft|download|downloaded|file|files|"
    r"upload|uploaded|attachment|asset|assets|hero|banner|bg|background|"
    r"placeholder|temp|tmp|test|output|export|render)$", re.I)


def _is_machine_formatted(alt: str) -> bool:
    """True when the alt reads like a file name rather than typed text: an
    image extension, a 3+ digit run, an underscore, a hyphenated slug where at
    least one segment is a filler/CMS word ('hero-banner-final'), or an
    auto-generated stem such as 'DSC_0042'.

    A no-space hyphenated string is NOT enough on its own -- ordinary compound
    words and brand names ('coca-cola', 'e-commerce', 'seven-eleven') are
    written exactly that way and must stay 'descriptive' even when they equal
    the file name."""
    s = alt.strip()
    bare = _IMAGE_EXT_RX.sub("", s)
    if _IMAGE_EXT_RX.search(s) or re.search(r"\d{3,}", s):
        return True
    if " " not in s and "_" in s:
        return True
    if _AUTOGEN_FILENAME_RX.match(bare):
        return True
    if " " not in s and "-" in s and s == s.lower():
        segs = [seg for seg in re.split(r"[-_.\s]+", bare) if seg]
        if any(_FILLER_WORD_RX.match(seg) for seg in segs):
            return True
    return False


def _classify_alt(alt_val, src=None) -> str:
    """Return one of: 'missing' | 'decorative' | 'generic' | 'descriptive'.

    An alt that is itself auto-generated-looking ('IMG_2041', 'hero-bg') is
    generic. When `src` is supplied, an alt that merely repeats the file name is
    generic only if it is also machine-formatted: alt="team_photo_02" on
    team_photo_02.jpg was copied from the file, but alt="Canva" on canva.png is
    a correct, human-written label for a logo. Short alts are not penalised just
    because the file name is a hash -- the alt is what the crawler reads."""
    if alt_val is None:
        return "missing"
    stripped = alt_val.strip()
    if stripped == "":
        return "decorative"
    low = stripped.lower()
    if low in GENERIC_ALT_TERMS or GENERIC_ALT_RX.match(low):
        return "generic"
    # Camera / CMS stems typed into the alt ('IMG_2041', 'DSC00192.jpg'). Needs
    # a digit, separator or extension so a long real word is never caught.
    bare = _IMAGE_EXT_RX.sub("", stripped)
    if (_AUTOGEN_FILENAME_RX.match(bare) and " " not in bare
            and (re.search(r"[\d_\-]", bare) or bare != stripped)):
        return "generic"
    if src:
        stem = _filename_stem(src).lower()
        if stem and _IMAGE_EXT_RX.sub("", low).strip() == stem and _is_machine_formatted(stripped):
            return "generic"
    return "descriptive"


def _snippet(tag: str, attrs: dict, max_len: int = 120) -> str:
    """Build a compact representative HTML snippet string for evidence."""
    parts = [f"<{tag}"]
    for k, v in attrs.items():
        if v is None:
            parts.append(f" {k}")
        else:
            v_display = v[:60] + "…" if len(v) > 60 else v
            parts.append(f' {k}="{v_display}"')
    parts.append(">")
    result = "".join(parts)
    return result[:max_len] + ("…" if len(result) > max_len else "")


def _is_icon_class(class_str: str) -> bool:
    c = class_str.lower()
    return any(frag in c for frag in ICON_CLASS_FRAGMENTS)


