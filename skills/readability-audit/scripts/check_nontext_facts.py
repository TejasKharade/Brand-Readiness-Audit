class NonTextMediaParser(HTMLParser):
    """
    Single-pass parser that classifies all non-text media into 6 categories.
    Tracks SVG depth to avoid double-counting nested SVG children.
    """

    def __init__(self):
        super().__init__()

        # category 1: standard images
        self.standard_images = []   # list of {alt_class, snippet, src_hint}

        # category 2: vector graphics (inline SVG)
        self.vector_graphics = []   # list of {accessible, method, snippet}

        # category 3: embedded media
        self.embedded_media  = []   # list of {kind, platform, has_caption_track, snippet}

        # category 4: canvas
        self.canvas_elements = []   # list of {has_fallback, snippet}

        # category 5: icon elements
        self.icon_elements   = []   # list of {properly_handled, method, snippet}

        # category 6: linked docs (PDF hrefs)
        self.pdf_links       = []   # list of href strings (deduplicated later)

        # category 7: a link/button whose ONLY accessible content is an <img>
        # with alt="" -- distinct from a merely-decorative empty alt (correct
        # when a link/button has other text, an aria-label, or a non-empty-alt
        # image alongside it). This is an objective WCAG 2.4.4/4.1.2 failure
        # ("link/button has no discernible text"), not a stylistic judgment
        # call: the element is unlabeled for a screen reader AND for any
        # non-visual AI crawler trying to understand navigation, since alt=""
        # instructs both to treat the image as if it were not there at all.
        self.unlabeled_interactive_images = []   # list of {tag, snippet}

        # --- internal state ---
        # Stack, not a flat flag, so a nested container (a <button> inside an
        # <a>, or vice versa -- unusual but not invalid to encounter in the
        # wild) is judged independently while text/images at any depth still
        # count toward EVERY enclosing container: a <button>Buy</button>
        # inside an <a> makes the outer <a> labeled too, even though "Buy" is
        # only a direct child of the inner element.
        self._interactive_stack = []
        self._svg_depth           = 0    # depth inside <svg> tags
        self._svg_has_title       = False
        self._svg_has_desc        = False
        self._svg_aria_label      = None
        self._svg_aria_labelledby = None
        self._svg_aria_hidden     = False
        self._svg_role            = None
        self._svg_snippet         = ""

        self._canvas_depth        = 0
        self._canvas_inner_words  = 0
        self._canvas_snippet      = ""

        self._in_video            = False
        self._video_has_track     = False
        self._video_snippet       = ""
        self._in_audio            = False
        self._audio_has_track     = False
        self._audio_snippet       = ""

        self._in_picture          = False  # inside <picture> wrapper

    # ---- helpers ----

    def _flush_svg(self):
        """Commit the completed <svg> to vector_graphics list."""
        accessible = (
            self._svg_has_title
            or self._svg_has_desc
            or bool(self._svg_aria_label)
            or bool(self._svg_aria_labelledby)
            or self._svg_aria_hidden   # deliberately hidden — correctly decorative
        )
        method = None
        if self._svg_aria_hidden:
            method = "aria-hidden (decorative)"
        elif self._svg_has_title:
            method = "<title>"
        elif self._svg_has_desc:
            method = "<desc>"
        elif self._svg_aria_label:
            method = "aria-label"
        elif self._svg_aria_labelledby:
            method = "aria-labelledby"
        self.vector_graphics.append({
            "accessible": accessible,
            "method": method,
            "snippet": self._svg_snippet,
        })

    def _flush_canvas(self, has_fallback: bool):
        self.canvas_elements.append({
            "has_fallback": has_fallback,
            "snippet": self._canvas_snippet,
        })

    # ---- tag handlers ----

    def handle_starttag(self, tag, attrs):
        tag_lower  = tag.lower()
        attrs_dict = {k.lower(): (v or "") for k, v in attrs}
        role       = attrs_dict.get("role", "").lower().strip()
        aria_hid   = attrs_dict.get("aria-hidden", "").lower().strip() == "true"

        # ---- category 1: <img> ----
        if tag_lower == "img":
            alt_val  = attrs_dict.get("alt") if "alt" in attrs_dict else None
            full_src = attrs_dict.get("src") or attrs_dict.get("data-src") or ""
            alt_cls  = _classify_alt(alt_val, full_src)
            src_hint = full_src[:80]
            self.standard_images.append({
                "alt_class": alt_cls,
                "filename_autogenerated": _is_autogenerated_filename(full_src),
                "snippet":   _snippet(tag_lower, {"src": src_hint, "alt": alt_val}),
                "src_hint":  src_hint,
            })
            # Propagate to every OPEN interactive container (see the stack
            # comment above for why this is "every", not just the innermost).
            # "generic"/"descriptive" alt still gives the element SOME
            # accessible name, even if the wording is poor -- that's a
            # separate finding (missing/generic alt) handled above. Both
            # "decorative" (alt="") and "missing" (no alt attribute at all)
            # provide NO accessible name, so either one leaves a link/button
            # unlabeled exactly the same way if nothing else does either.
            for entry in self._interactive_stack:
                if alt_cls in ("decorative", "missing"):
                    entry["has_unlabeled_img"] = True
                    if entry["unlabeled_alt_kind"] is None:
                        entry["unlabeled_alt_kind"] = alt_cls
                else:
                    entry["has_labeling_img"] = True

        # ---- category 1: <source> inside <picture> ----
        elif tag_lower == "source" and self._in_picture:
            # <source> elements inherit alt from the sibling <img> — tracked separately
            pass   # No independent alt; counted only when <img> is absent in picture

        elif tag_lower == "picture":
            self._in_picture = True

        # ---- category 2: <svg> ----
        elif tag_lower == "svg":
            if self._svg_depth == 0:
                # Start tracking the outermost SVG
                self._svg_has_title       = False
                self._svg_has_desc        = False
                self._svg_aria_label      = attrs_dict.get("aria-label", "")
                self._svg_aria_labelledby = attrs_dict.get("aria-labelledby", "")
                self._svg_aria_hidden     = aria_hid
                self._svg_role            = role
                self._svg_snippet         = _snippet(tag_lower, {
                    k: v for k, v in attrs_dict.items()
                    if k in ("class", "role", "aria-label", "aria-hidden", "aria-labelledby")
                })
            self._svg_depth += 1

        # ---- SVG child: <title> or <desc> ----
        elif tag_lower in ("title", "desc") and self._svg_depth > 0:
            if tag_lower == "title":
                self._svg_has_title = True
            else:
                self._svg_has_desc = True

        # ---- category 3: <video> ----
        elif tag_lower == "video":
            self._in_video       = True
            self._video_has_track = False
            self._video_snippet  = _snippet(tag_lower, {
                k: v for k, v in attrs_dict.items()
                if k in ("src", "controls", "aria-label", "title")
            })

        elif tag_lower == "track" and self._in_video:
            kind = attrs_dict.get("kind", "").lower()
            if kind in ("captions", "subtitles", "descriptions", ""):
                self._video_has_track = True
        elif tag_lower == "track" and self._in_audio:
            self._audio_has_track = True

        # ---- category 3: <audio> ----
        elif tag_lower == "audio":
            self._in_audio       = True
            self._audio_has_track = False
            self._audio_snippet  = _snippet(tag_lower, {
                k: v for k, v in attrs_dict.items()
                if k in ("src", "controls", "aria-label", "title")
            })

        # ---- category 3: <iframe> (embedded video platforms) ----
        elif tag_lower == "iframe":
            src = attrs_dict.get("src", "")
            if YOUTUBE_PATTERN.search(src):
                platform = "YouTube"
            elif VIMEO_PATTERN.search(src):
                platform = "Vimeo"
            elif WISTIA_PATTERN.search(src):
                platform = "Wistia"
            elif LOOM_PATTERN.search(src):
                platform = "Loom"
            else:
                platform = None

            if platform:
                title_attr = attrs_dict.get("title", "")
                aria_label = attrs_dict.get("aria-label", "")
                self.embedded_media.append({
                    "kind":              "iframe_video",
                    "platform":          platform,
                    "has_caption_track": False,      # iframes can't have <track>
                    "has_title_attr":    bool(title_attr.strip()),
                    "has_aria_label":    bool(aria_label.strip()),
                    "snippet":           _snippet(tag_lower, {
                        "src":        src[:70],
                        "title":      title_attr or None,
                        "aria-label": aria_label or None,
                    }),
                })

        # ---- category 4: <canvas> ----
        elif tag_lower == "canvas":
            self._canvas_depth   = 1
            self._canvas_inner_words = 0
            self._canvas_snippet = _snippet(tag_lower, {
                k: v for k, v in attrs_dict.items()
                if k in ("id", "class", "aria-label", "role")
            })

        # ---- category 5: icon elements ----
        # <i class="fa-..."> or <span class="icon-..."> or any element with role="img"
        elif tag_lower in ("i", "span") or role == "img":
            class_val = attrs_dict.get("class", "")
            is_icon   = _is_icon_class(class_val)
            if is_icon or role == "img":
                aria_label = attrs_dict.get("aria-label", "").strip()
                aria_lby   = attrs_dict.get("aria-labelledby", "").strip()
                title_attr = attrs_dict.get("title", "").strip()
                properly_handled = (
                    aria_hid
                    or bool(aria_label)
                    or bool(aria_lby)
                    or bool(title_attr)
                )
                if aria_hid:
                    method = "aria-hidden (decorative)"
                elif aria_label:
                    method = "aria-label"
                elif aria_lby:
                    method = "aria-labelledby"
                elif title_attr:
                    method = "title attribute"
                else:
                    method = None
                self.icon_elements.append({
                    "properly_handled": properly_handled,
                    "method":           method,
                    "snippet":          _snippet(tag_lower, {
                        "class":       class_val[:50] or None,
                        "role":        role or None,
                        "aria-label":  aria_label or None,
                        "aria-hidden": "true" if aria_hid else None,
                    }),
                })

        # ---- category 6: PDF links ----
        if tag_lower == "a":
            href = attrs_dict.get("href", "")
            if href:
                path = urllib.parse.urlparse(href).path.lower()
                if path.endswith(".pdf"):
                    self.pdf_links.append(href)

        # ---- category 7: track a candidate link/button for the unlabeled-
        # interactive-image check. An <a> with no href is a named anchor, not
        # a link, so it is not tracked; any <button> qualifies regardless.
        if (tag_lower == "a" and attrs_dict.get("href")) or tag_lower == "button":
            aria_label = attrs_dict.get("aria-label", "").strip()
            title_attr = attrs_dict.get("title", "").strip()
            self._interactive_stack.append({
                "tag": tag_lower,
                "has_text": False,
                "has_label": bool(aria_label) or bool(title_attr),
                "has_labeling_img": False,
                "has_unlabeled_img": False,
                "unlabeled_alt_kind": None,
                "snippet": _snippet(tag_lower, {
                    k: v for k, v in attrs_dict.items()
                    if k in ("href", "class", "aria-label", "title")
                }),
            })

    def handle_endtag(self, tag):
        tag_lower = tag.lower()

        if tag_lower == "picture":
            self._in_picture = False

        elif tag_lower == "svg" and self._svg_depth > 0:
            self._svg_depth -= 1
            if self._svg_depth == 0:
                self._flush_svg()

        elif tag_lower == "video" and self._in_video:
            self.embedded_media.append({
                "kind":              "video",
                "platform":          "native",
                "has_caption_track": self._video_has_track,
                "has_title_attr":    False,
                "has_aria_label":    False,
                "snippet":           self._video_snippet,
            })
            self._in_video = False

        elif tag_lower == "audio" and self._in_audio:
            self.embedded_media.append({
                "kind":              "audio",
                "platform":          "native",
                "has_caption_track": self._audio_has_track,
                "has_title_attr":    False,
                "has_aria_label":    False,
                "snippet":           self._audio_snippet,
            })
            self._in_audio = False

        elif tag_lower == "canvas" and self._canvas_depth > 0:
            self._canvas_depth = 0
            self._flush_canvas(has_fallback=(self._canvas_inner_words > 0))

        if (tag_lower in ("a", "button") and self._interactive_stack
                and self._interactive_stack[-1]["tag"] == tag_lower):
            entry = self._interactive_stack.pop()
            if (entry["has_unlabeled_img"] and not entry["has_text"]
                    and not entry["has_label"] and not entry["has_labeling_img"]):
                self.unlabeled_interactive_images.append({
                    "tag": entry["tag"],
                    "alt_kind": entry["unlabeled_alt_kind"],
                    "snippet": entry["snippet"],
                })

    def handle_data(self, data):
        if self._canvas_depth > 0 and data.strip():
            self._canvas_inner_words += len(data.split())
        if self._interactive_stack and data.strip():
            for entry in self._interactive_stack:
                entry["has_text"] = True


# ---------------------------------------------------------------------------
# PDF text-layer heuristic (stdlib only — no pypdf, no requests)
# ---------------------------------------------------------------------------

_PDF_TEXT_OP_RX   = re.compile(rb"BT\b[\s\S]{0,4000}?(?:Tj|TJ|'|\")")   # BT ... Tj/TJ
_PDF_STREAM_RX    = re.compile(rb"stream\r?\n([\s\S]*?)\r?\nendstream")
_PDF_MAX_STREAMS  = 25
_PDF_MAX_STREAM_BYTES = 3 * 1024 * 1024
_PDF_HARD_CEIL_BYTES  = 10 * 1024 * 1024

# Wall-clock ceiling across ALL linked-PDF inspections on one page. Every other
# network-bound script in this marketplace enforces one (check_sitemap.py 30s,
# check_page_speed_signals.py 20s, fetch_dual_identity.py 20s); this loop was
# the only one that did not, and a per-request `timeout` does not bound it: the
# socket timeout resets on every chunk that arrives, so a server trickling a
# 1 MB PDF a few bytes at a time never trips it and the audit hangs past the
# handout's <5 min runtime constraint. 25s is deliberately just above the
# nominal cost of the default 3 PDFs x 8s per-request timeout, so a healthy
# site's behaviour is completely unchanged -- this only ever fires on a
# pathologically slow host.
PDF_INSPECTION_DEADLINE_S = 25.0


def _scan_bytes_for_text_ops(buf: bytes) -> bool:
    if not buf:
        return False
    if _PDF_TEXT_OP_RX.search(buf):
        return True
    # positional text operators used without an explicit BT/ET wrapper in some writers
    return bool(re.search(rb"\b(Td|TD|Tf|Tj|TJ)\b", buf) and re.search(rb"\bTf\b", buf))


def inspect_pdf_stdlib(pdf_url: str, base_url: str, timeout: int = 8,
                       max_bytes: int = 1024 * 1024, gate=None) -> dict:
    """
    Fetches the first `max_bytes` (default 1 MB, hard ceiling 10 MB) of a PDF
    and decides whether it carries an extractable digital text layer.

    Detection order (first match wins):
      1. tagged-PDF structure  (/MarkInfo /Marked true  or  /StructTreeRoot)
      2. /ToUnicode CMap present (font-to-text mapping -> real selectable text)
      3. uncompressed text-drawing operators in the raw bytes  (BT ... Tj/TJ)
      4. FlateDecode (zlib) content streams inflated, then scanned for the
         same text operators  -- this is what the old byte-header heuristic
         missed, since almost every real PDF Flate-compresses its content
      5. /Subtype /Image XObject present and NO text operators anywhere
         -> image-only / scanned  (has_text_layer = False)
      6. otherwise, if the fetch was truncated -> None (inconclusive), never a
         false "no text layer"
    """
    abs_url = urllib.parse.urljoin(base_url, pdf_url) if base_url else pdf_url
    max_bytes = max(64 * 1024, min(int(max_bytes), _PDF_HARD_CEIL_BYTES))
    result  = {
        "url":               abs_url,
        "http_status":       None,
        "byte_size_fetched": None,
        "has_text_layer":    None,
        "method":            None,
        "streams_found":     0,
        "streams_inflated":  0,
        "truncated":         None,
        "error":             None,
    }
    try:
        req = urllib.request.Request(
            abs_url,
            headers={
                "User-Agent": "Mozilla/5.0 (compatible; BrandAIAuditor/2.0)",
                "Range":      f"bytes=0-{max_bytes - 1}",
            }
        )
        # Read in chunks against a wall-clock budget rather than one blocking
        # `resp.read(max_bytes)`. The socket `timeout` only bounds the gap
        # BETWEEN chunks -- it resets every time a byte arrives -- so a host
        # trickling a 1 MB PDF a few bytes at a time never trips it and this
        # single call would hang indefinitely, taking the whole audit past the
        # <5 min runtime constraint with it. `read1` returns whatever has
        # actually arrived instead of blocking for a full buffer, so the
        # deadline below is checked promptly rather than once per 64 KB.
        _read_start = time.time()
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            result["http_status"] = resp.status
            _read1 = getattr(resp, "read1", None) or resp.read
            chunks, got = [], 0
            while got < max_bytes:
                if time.time() - _read_start > timeout:
                    result["read_deadline_exceeded"] = True
                    break
                chunk = _read1(min(65536, max_bytes - got))
                if not chunk:
                    break
                chunks.append(chunk)
                got += len(chunk)
            raw = b"".join(chunks)
        result["byte_size_fetched"] = len(raw)
        # A budget-truncated read is truncated in the same sense as a
        # size-truncated one: downstream must treat an inconclusive scan as
        # has_text_layer=None, never as "this PDF has no text layer".
        result["truncated"] = len(raw) >= max_bytes or bool(result.get("read_deadline_exceeded"))

        if not raw.startswith(PDF_MAGIC):
            result["error"] = "Response does not start with PDF magic bytes (%PDF)"
            result["has_text_layer"] = False
            result["method"] = "not_a_pdf"
            return result

        # 1. tagged PDF structure
        if re.search(rb"/MarkInfo\b[\s\S]{0,60}/Marked\s*/?true", raw) or \
           re.search(rb"/StructTreeRoot\b", raw):
            result["has_text_layer"] = True
            result["method"] = "tagged_structure"
            return result

        # 2. font-to-unicode mapping
        if re.search(rb"/ToUnicode\b", raw):
            result["has_text_layer"] = True
            result["method"] = "tounicode_cmap"
            return result

        # 3. uncompressed text operators
        if _scan_bytes_for_text_ops(raw):
            result["has_text_layer"] = True
            result["method"] = "uncompressed_text_operators"
            return result

        # 4. inflate FlateDecode streams and scan
        streams = _PDF_STREAM_RX.findall(raw)
        result["streams_found"] = len(streams)
        inflated = 0
        for s in streams[:_PDF_MAX_STREAMS]:
            if not s or len(s) > _PDF_MAX_STREAM_BYTES:
                continue
            for wbits in (15, -15, 47):
                try:
                    dec = zlib.decompress(s, wbits)
                except Exception:
                    continue
                inflated += 1
                if _scan_bytes_for_text_ops(dec):
                    result["streams_inflated"] = inflated
                    result["has_text_layer"] = True
                    result["method"] = "flate_decoded_text_operators"
                    return result
                break
        result["streams_inflated"] = inflated

        # 5. image XObject present, no text found anywhere
        if re.search(rb"/Subtype\s*/Image\b", raw):
            if result["truncated"]:
                result["has_text_layer"] = None
                result["method"] = "image_xobject_no_text_but_truncated"
            else:
                result["has_text_layer"] = False
                result["method"] = "image_xobject_no_text"
            return result

        # 6. inconclusive
        if result["truncated"]:
            result["has_text_layer"] = None
            result["method"] = "inconclusive_truncated"
        else:
            result["has_text_layer"] = False
            result["method"] = "no_text_operators_found"
        return result

    except urllib.error.HTTPError as e:
        result["http_status"] = e.code
        result["error"]       = f"HTTP {e.code}"
    except Exception as e:
        result["error"] = str(e)[:120]
    return result


