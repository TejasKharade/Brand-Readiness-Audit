import threading


def read_stdin_safe(timeout: float = 0.2) -> str:
    if sys.stdin.isatty():
        return ""
    res = []
    def _target():
        try:
            res.append(sys.stdin.read())
        except Exception:
            pass
    t = threading.Thread(target=_target, daemon=True)
    t.start()
    t.join(timeout=timeout)
    return res[0].lstrip("\ufeff") if res else ""


if __name__ == "__main__":
    try:
        html_content = ""
        url          = ""
        params       = {}

        if len(sys.argv) > 1:
            raw_arg = sys.argv[1].strip()
            if raw_arg.startswith("{"):
                try:
                    params       = json.loads(raw_arg)
                    html_content = params.get("html", "") or params.get("raw_html", "")
                    url          = params.get("url", "")
                except json.JSONDecodeError:
                    url = raw_arg
            else:
                url = raw_arg

        input_data = read_stdin_safe(timeout=1.0 if len(sys.argv) > 1 else 5.0)
        if input_data.strip():
            try:
                sp = json.loads(input_data)
                if isinstance(sp, dict):
                    params.update(sp)
            except json.JSONDecodeError:
                pass

        if not html_content:
            html_content = params.get("html", "") or params.get("raw_html", "")
        if not url:
            url = params.get("url", "")

        result = check_nontext_facts(html_content, url, robots=params.get("robots"))
        print(json.dumps(result, indent=2))
    except Exception as e:
        print(json.dumps({"error": f"Script execution failed: {str(e)}"}))

