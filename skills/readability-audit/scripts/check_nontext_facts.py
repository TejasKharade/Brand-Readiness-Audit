# ---------------------------------------------------------------------------
# Generic / placeholder alt-text terms (case-insensitive exact match)
# ---------------------------------------------------------------------------
GENERIC_ALT_TERMS = {
    "image", "photo", "picture", "banner", "logo", "icon", "graphic",
    "img", "placeholder", "untitled", "thumbnail", "figure", "screenshot",
    "test", "temp", "default", "hero", "header image", "cover", "cover image",
    "spacer", "divider", "blank", "no image", "n/a",
}

# A single generic word optionally followed by a number/letter suffix
# ("image", "photo 2", "banner-3", "img_04", "picture (1)") -- replaces the old
# enumerated "image 1 / image 2 / image 3" entries with one pattern.
GENERIC_ALT_RX = re.compile(
    r"^(image|images|photo|photos|picture|pic|pics|banner|logo|icon|graphic|"
    r"img|figure|fig|thumbnail|thumb|screenshot|slide|item|product|gallery)"
    r"[\s._\-]*\(?\d*\)?[a-z]?$",
    re.I,
)

# Auto-generated / camera / CMS-export filename stems (no extension, lowercased).
# Detects names that carry no descriptive information regardless of the alt text.
_AUTOGEN_FILENAME_RX = re.compile(
    r"^("
    r"(img|image|images|dsc|dscn|dscf|pxl|gopr|mvimg|pano|photo|pic|scan|scanned|"
    r"capture|screenshot|screen[\s._-]?shot|screen[\s._-]?capture|snip|snap|"
    r"untitled|unnamed|noname|new|final|final2|finalfinal|copy|copyof|draft|"
    r"download|downloaded|file|files|upload|uploaded|attachment|asset|assets|"
    r"hero|banner|bg|background|placeholder|temp|tmp|test|output|export|render)"
    r"[\s._\-]*\(?\d*\)?"
    r"|\d{3,}"                              # 1633024800  (timestamps / ids)
    r"|[0-9a-f]{8,}"                        # deadbeefcafe (hex hashes)
    r"|[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}"  # uuid
    r"|[a-z0-9]{20,}"                       # long CMS content hashes
    r")$",
    re.I,
)


def _filename_stem(src: str) -> str:
    if not src:
        return ""
    path = src.split("?")[0].split("#")[0]
    base = path.rstrip("/").split("/")[-1]
    if "." in base:
        base = base.rsplit(".", 1)[0]
    return base.strip()


def _is_autogenerated_filename(src: str) -> bool:
    stem = _filename_stem(src)
    if not stem or len(stem) < 3:
        return False
    return bool(_AUTOGEN_FILENAME_RX.match(stem))

# Icon-font class fragments that indicate a decorative/icon element
ICON_CLASS_FRAGMENTS = (
    "fa-", "fa ", "fas ", "far ", "fal ", "fab ", "fad ",   # Font Awesome
    "glyphicon", "material-icons", "icon-", "bi-", "bi ",  # Bootstrap / Material / etc.
    "mdi-", "mdi ", "feather-", "heroicon",
    "sprite", "svg-icon", "icon icon", "ico-",
)

# Embedded media host patterns (iframe src)
YOUTUBE_PATTERN  = re.compile(r"youtube\.com|youtu\.be", re.I)
VIMEO_PATTERN    = re.compile(r"vimeo\.com", re.I)
WISTIA_PATTERN   = re.compile(r"wistia\.(com|net)", re.I)
LOOM_PATTERN     = re.compile(r"loom\.com", re.I)

# PDF magic bytes (first 4 bytes of every PDF file)
PDF_MAGIC = b"%PDF"


