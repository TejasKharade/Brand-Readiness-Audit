def check_nontext_facts(html_content: str, url: str = "", max_pdfs: int = 3, robots=None) -> dict:
    parser = NonTextMediaParser()
    try:
        parser.feed(html_content or "")
    except Exception:
        pass

    # ---- 1. Standard images ----
    imgs = parser.standard_images
    img_total       = len(imgs)
    img_missing     = sum(1 for i in imgs if i["alt_class"] == "missing")
    img_decorative  = sum(1 for i in imgs if i["alt_class"] == "decorative")
    img_generic     = sum(1 for i in imgs if i["alt_class"] == "generic")
    img_descriptive = sum(1 for i in imgs if i["alt_class"] == "descriptive")
    img_autogen_fn  = sum(1 for i in imgs if i.get("filename_autogenerated"))
    # Representative snippet of first missing-alt image
    first_missing_img_snippet = next(
        (i["snippet"] for i in imgs if i["alt_class"] == "missing"), None
    )
    first_generic_img_snippet = next(
        (i["snippet"] for i in imgs if i["alt_class"] == "generic"), None
    )

    # ---- 2. Vector graphics ----
    svgs = parser.vector_graphics
    svg_total       = len(svgs)
    svg_accessible  = sum(1 for s in svgs if s["accessible"])
    svg_inaccessible = svg_total - svg_accessible
    first_bad_svg_snippet = next(
        (s["snippet"] for s in svgs if not s["accessible"]), None
    )

    # ---- 3. Embedded media ----
    media = parser.embedded_media
    videos          = [m for m in media if m["kind"] == "video"]
    audios          = [m for m in media if m["kind"] == "audio"]
    iframe_videos   = [m for m in media if m["kind"] == "iframe_video"]
    video_no_cap    = [v for v in videos    if not v["has_caption_track"]]
    audio_no_cap    = [a for a in audios    if not a["has_caption_track"]]
    iframe_no_title = [i for i in iframe_videos if not i["has_title_attr"] and not i["has_aria_label"]]
    first_video_snippet       = videos[0]["snippet"]       if videos else None
    first_iframe_snippet      = iframe_videos[0]["snippet"] if iframe_videos else None

    # ---- 4. Canvas ----
    canvases        = parser.canvas_elements
    canvas_total    = len(canvases)
    canvas_no_fallback = sum(1 for c in canvases if not c["has_fallback"])
    first_canvas_snippet = canvases[0]["snippet"] if canvases else None

    # ---- 5. Icon elements ----
    icons           = parser.icon_elements
    icon_total      = len(icons)
    icon_ok         = sum(1 for ic in icons if ic["properly_handled"])
    icon_unlabelled = icon_total - icon_ok
    first_bad_icon_snippet = next(
        (ic["snippet"] for ic in icons if not ic["properly_handled"]), None
    )

    # ---- 6. Linked PDFs ----
    seen_pdfs = []
    seen_set  = set()
    for h in parser.pdf_links:
        if h not in seen_set:
            seen_set.add(h)
            seen_pdfs.append(h)

    pdf_results = []
    # Downloading a linked PDF is a fetch of that URL; sites commonly disallow
    # /files/ or /wp-content/uploads/ precisely to keep crawlers out of them.
    _gate = RobotsGate.for_url(url, robots=robots) if RobotsGate else None
    _pdf_start = time.time()
    for href in seen_pdfs[:max_pdfs]:
        if _gate is not None:
            _decision = _gate.allows(href, "*")
            if not _decision.allowed:
                pdf_results.append({"url": href, "skipped_by_robots": True,
                                    "has_text_layer": None, "error": _decision.reason})
                continue
        _left = PDF_INSPECTION_DEADLINE_S - (time.time() - _pdf_start)
        if _left <= 1.0:
            # Budget spent. Report the PDF as NOT MEASURED (has_text_layer stays
            # None), never as "no text layer" -- an unread PDF is not a defect.
            pdf_results.append({
                "url": href, "has_text_layer": None, "deadline_exceeded": True,
                "error": f"skipped: {PDF_INSPECTION_DEADLINE_S:.0f}s PDF-inspection budget exceeded"})
            continue
        pdf_results.append(inspect_pdf_stdlib(
            href, url, timeout=int(max(2, min(8, _left))), gate=_gate))

    pdf_no_text = [p for p in pdf_results if p.get("has_text_layer") is False]

    # ---- Aggregate accessibility scores ----
    images_without_alt_count = img_missing + img_generic   # combined problem count

    return {
        # Legacy flat key kept for backward-compat with older synthesize_report check
        "images_without_alt_count": images_without_alt_count,

        # ---- Category 1 ----
        "standard_images": {
            "total":                      img_total,
            "missing_alt":                img_missing,
            "decorative_alt_empty":       img_decorative,
            "generic_alt_placeholder":    img_generic,
            "descriptive_alt":            img_descriptive,
            "autogenerated_filename_count": img_autogen_fn,
            "first_missing_alt_snippet":  first_missing_img_snippet,
            "first_generic_alt_snippet":  first_generic_img_snippet,
        },

        # ---- Category 2 ----
        "vector_graphics": {
            "total":                      svg_total,
            "accessible":                 svg_accessible,
            "inaccessible":               svg_inaccessible,
            "first_inaccessible_snippet": first_bad_svg_snippet,
        },

        # ---- Category 3 ----
        "embedded_media": {
            "video_total":                len(videos),
            "video_missing_captions":     len(video_no_cap),
            "audio_total":                len(audios),
            "audio_missing_captions":     len(audio_no_cap),
            "iframe_video_total":         len(iframe_videos),
            "iframe_video_missing_title": len(iframe_no_title),
            "first_video_snippet":        first_video_snippet,
            "first_iframe_snippet":       first_iframe_snippet,
        },

        # ---- Category 4 ----
        "canvas_and_interactive": {
            "total":               canvas_total,
            "missing_fallback":    canvas_no_fallback,
            "first_snippet":       first_canvas_snippet,
        },

        # ---- Category 5 ----
        "icon_elements": {
            "total":               icon_total,
            "properly_handled":    icon_ok,
            "unlabelled":          icon_unlabelled,
            "first_bad_snippet":   first_bad_icon_snippet,
        },

        # ---- Category 6 ----
        "linked_documents": {
            "pdf_links_found":     len(seen_pdfs),
            "pdf_links_inspected": len(pdf_results),
            "pdf_missing_text_layer": len(pdf_no_text),
            "details":             pdf_results,
        },

        # ---- Category 7 ----
        # A link/button whose ONLY content is an <img> with alt="" (or no alt
        # at all) and no other text/aria-label/title/labeling-image alongside
        # it. Distinct from `standard_images.decorative_alt_empty`, which
        # counts EVERY alt="" image, most of which are correctly decorative
        # (a spacer, a background flourish) -- flagging all of those would be
        # a false-positive generator penalising sites for following W3C
        # guidance. This category is narrower and unambiguous: the element
        # has no accessible name at all, an objective WCAG 2.4.4/4.1.2
        # failure, not a stylistic judgment call.
        "unlabeled_interactive_images": {
            "count":   len(parser.unlabeled_interactive_images),
            "details": parser.unlabeled_interactive_images[:10],
        },
    }


